#!/usr/bin/env python3
"""把 Einfacht 的闸门接到你的仓库 —— **不抢钩子座位**。

## 为什么不 `git config core.hooksPath`

`core.hooksPath` 是 git 的**全局覆盖开关**：一旦设上，git 就**完全不再看**
`.git/hooks/`。实测：设了之后 `.git/hooks/pre-commit` 一次都不跑，提交照样成功、
**没有任何提示**。于是 husky / lefthook / pre-commit(Python) / 手写钩子全被
**静默废掉** —— 正是本仓立身要消灭的「部署了 ≠ 在跑」。

所以本仓只**暴露一个入口**（`reflect-hooks/gate.py`），钩子位置归你自己。

## 四种接入，都可逆

    （无参数）[目标仓]   打印接入说明，**不写任何文件**
    --chain             装 `.git/hooks/` 的**链式** wrapper（已有同名钩子 ⇒
                        先跑它，再跑 Einfacht）
    --legacy            旧装法（`core.hooksPath`）—— **会覆盖** `.git/hooks`
    --uninstall         撤销（两种装法都认）

## 为什么用 Python

此前是 `install.sh`（138 行 shell，12 处 `echo` 中文）。它绕过了零语言制度
（`check_i18n` 只扫 `.py`），且 Windows 上没有可靠的 `sh`。

**生成的 hook wrapper 仍然是 shell** —— 那是 git 调的东西，必须是最小可执行
文件；但它由本脚本生成、内容固定、**不含任何用户可见的中文**（只有一行 exec
与一段固定注释）。
"""
from __future__ import annotations

import os
import stat
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL_REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(TOOL_REPO, "zreflect"))

from gate import activate_or_fatal, meta  # noqa: E402
from i18n import M  # noqa: E402

GATE = os.path.join(HERE, "gate.py")
PHASE_OF = {"pre-commit": "commit", "pre-push": "push"}


def _git(repo, *args):
    try:
        p = subprocess.run(["git", "-C", repo, *args],
                           capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
    except (OSError, subprocess.SubprocessError):
        return None, ""
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def _chmod_x(path):
    mode = os.stat(path).st_mode
    os.chmod(path, mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def _wrapper_body(name, phase):
    """链式 wrapper 的内容。**固定**、含一行 exec、无中文。"""
    return (
        "#!/bin/sh\n"
        "# Einfacht chain wrapper (generated by reflect-hooks/install.py --chain)\n"
        'HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)\n'
        'PREV="$HERE/%s.einfacht-prev"\n'
        'if [ -x "$PREV" ]; then\n'
        '  "$PREV" "$@" || exit $?\n'
        "fi\n"
        'exec python3 "%s" %s "$(git rev-parse --show-toplevel)"\n'
        % (name, GATE, phase)
    )


def install_chain(repo):
    """装链式 wrapper。返回 (rc, lines)。

    ⚠️ **先查 `core.hooksPath`**：git 一旦设了它，就**完全不看 `.git/hooks`**。
    此时在这里写 wrapper 是**写了也不会被执行** —— 装完之后 `git commit`
    看起来一切正常，`installed chain` 也打印了，而钩子一次都没跑。
    实测：一个仓已有 `core.hooksPath=reflect-hooks`（旧的 `--legacy` 装法），
    `--chain` 返回 0 且零警告，`.git/hooks/pre-commit` 里的 wrapper 是死的。

    这是本仓立身要消灭的「部署了 ≠ 在跑」—— 所以**当场报，不装**。
    """
    hooks = os.path.join(repo, ".git", "hooks")
    if not os.path.isdir(hooks):
        return 2, [str(M("install.no_hooks_dir", path=hooks))]
    rc, current = _git(repo, "config", "core.hooksPath")
    if rc == 0 and (current or "").strip():
        # 已有一个 core.hooksPath ⇒ `.git/hooks` 被 git 忽略。装 chain 是空转。
        return 2, [str(M("install.chain_blocked_by_hookspath",
                         value=current.strip())),
                   str(M("install.chain_blocked_fix"))]
    lines = []
    for name, phase in PHASE_OF.items():
        target = os.path.join(hooks, name)
        prev = target + ".einfacht-prev"
        if os.path.isfile(target):
            try:
                body = open(target, encoding="utf-8", errors="replace").read()
            except OSError:
                body = ""
            if "gate.py" not in body and "einfacht-gate.sh" not in body:
                os.replace(target, prev)
                lines.append(str(M("install.kept_existing", name=name)))
        with open(target, "w", encoding="utf-8") as fh:
            fh.write(_wrapper_body(name, phase))
        _chmod_x(target)
        lines.append(str(M("install.installed_chain", name=name)))
    lines.append(str(M("install.chain_done")))
    return 0, lines


def install_legacy(repo):
    """旧装法：`core.hooksPath reflect-hooks`。返回 (rc, lines)。"""
    _rc, _out = _git(repo, "config", "core.hooksPath", "reflect-hooks")
    for n in PHASE_OF:
        p = os.path.join(HERE, n)
        if os.path.isfile(p):
            _chmod_x(p)
    _rc2, got = _git(repo, "config", "core.hooksPath")
    return 0, [str(M("install.legacy_mounted", value=(got or "").strip())),
               str(M("install.legacy_warning")),
               str(M("install.uninstall_hint"))]


def uninstall(repo):
    """撤销两种装法。返回 (rc, lines)。"""
    lines = []
    rc, _o = _git(repo, "config", "--unset", "core.hooksPath")
    lines.append(str(M("install.legacy_removed")) if rc == 0
                 else str(M("install.legacy_was_not_set")))
    hooks = os.path.join(repo, ".git", "hooks")
    for name in PHASE_OF:
        target = os.path.join(hooks, name)
        prev = target + ".einfacht-prev"
        if os.path.isfile(target):
            try:
                body = open(target, encoding="utf-8", errors="replace").read()
            except OSError:
                body = ""
            if "gate.py" in body or "einfacht-gate.sh" in body:
                os.unlink(target)
                lines.append(str(M("install.chain_removed", name=name)))
        if os.path.isfile(prev):
            os.replace(prev, target)
            lines.append(str(M("install.restored_original", name=name)))
    return 0, lines


def usage_lines(repo):
    return [str(M("install.usage")),
            str(M("install.usage_no_target")),
            str(M("install.usage_chain")),
            str(M("install.usage_legacy")),
            str(M("install.usage_uninstall"))]


def instructions(repo):
    """无参数：接入说明（**不写任何文件**）。"""
    return [str(M("install.intro")),
            str(M("install.example_commit", gate=GATE)),
            str(M("install.example_push", gate=GATE)),
            str(M("install.chain_hint")),
            str(M("install.uninstall_hint")),
            str(M("install.why_not_hookspath"))]


def main(argv):
    mode = argv[0] if argv else ""
    target = argv[1] if len(argv) > 1 else ""
    repo = os.path.abspath(target) if target else TOOL_REPO
    if target and not os.path.isdir(os.path.join(repo, ".git")):
        print(str(M("install.not_a_repo", path=repo)), file=sys.stderr)
        return 2
    if mode in ("--help", "-h"):
        print("\n".join(usage_lines(repo)))
        return 0
    if mode == "":
        print("\n".join(instructions(repo)))
        return 0
    if mode == "--chain":
        rc, lines = install_chain(repo)
    elif mode == "--legacy":
        rc, lines = install_legacy(repo)
    elif mode == "--uninstall":
        rc, lines = uninstall(repo)
    else:
        print("\n".join(usage_lines(repo)), file=sys.stderr)
        return 2
    for ln in lines:
        print(ln, file=(sys.stderr if rc else sys.stdout))
    return rc


# ── 自证 ──────────────────────────────────────────────────────────────────────

def _cases():
    import shutil
    import tempfile  # noqa: PLC0415

    def mk():
        d = tempfile.mkdtemp()
        _git(d, "init", "-q")
        return d

    return [
        # ① 正常不报：无参数 ⇒ 只打印、退 0、**不写任何文件**
        ("install.no_args_prints_only", lambda: _no_args_case(mk, shutil)),
        # ② 该报的必须报
        ("★ install.unknown_mode_is_2",
         lambda: _run_cli(["--bogus"], quiet=True) == 2),
        ("★ install.not_a_repo_is_2",
         lambda: _run_cli(["--chain", "/nonexistent-xyz"], quiet=True) == 2),
        # chain 真的装了 wrapper 且**保留**原有钩子
        ("★ install.chain_keeps_existing", lambda: _chain_case(mk, shutil)),
        # uninstall 真的恢复原有钩子
        ("★ install.uninstall_restores", lambda: _uninstall_case(mk, shutil)),
        # **已有 core.hooksPath ⇒ 拒绝装 chain**（装了也不会跑）。
        # 这是「部署了 ≠ 在跑」家族 —— 本仓立身要消灭的那一类。
        ("★ install.chain_refused_when_hookspath_set",
         lambda: _chain_blocked_case(mk, shutil)),
        # ③ 空输入必须报：仓里没有 .git/hooks
        ("★ install.missing_hooks_dir_is_2",
         lambda: _missing_hooks_case(mk, shutil)),
    ]


def _run_cli(argv, quiet=False):
    """走一遍 CLI 分派，返回 rc。

    `quiet=True`（**自证专用**）：不打印 —— 自证输出是给人核对的接口。
    此前自证里它会打印 usage / 接入说明，那些行排在机器摘要行之后，
    harness 取「最后一行当摘要」时拿到的是它们（实测，与 gate.py 同一个病）。
    """
    if quiet:
        import contextlib  # noqa: PLC0415
        import io  # noqa: PLC0415
        with contextlib.redirect_stdout(io.StringIO()), \
                contextlib.redirect_stderr(io.StringIO()):
            return main(argv)
    return main(argv)


def _no_args_case(mk, shutil):
    d = mk()
    try:
        before = set(os.listdir(os.path.join(d, ".git", "hooks")))
        rc = _run_cli([], quiet=True)
        after = set(os.listdir(os.path.join(d, ".git", "hooks")))
        return rc == 0 and before == after
    finally:
        shutil.rmtree(d, True)


def _chain_case(mk, shutil):
    d = mk()
    try:
        hooks = os.path.join(d, ".git", "hooks")
        pre = os.path.join(hooks, "pre-commit")
        open(pre, "w", encoding="utf-8").write("#!/bin/sh\necho mine\n")
        _chmod_x(pre)
        rc, _lines = install_chain(d)
        prev = pre + ".einfacht-prev"
        body = open(pre, encoding="utf-8").read()
        return rc == 0 and os.path.isfile(prev) and "gate.py" in body
    finally:
        shutil.rmtree(d, True)


def _chain_blocked_case(mk, shutil):
    """已有 `core.hooksPath` 时，`--chain` 必须 rc=2 **且不写 wrapper**。"""
    d = mk()
    try:
        _git(d, "config", "core.hooksPath", "reflect-hooks")
        rc, _lines = install_chain(d)
        wrapper = os.path.join(d, ".git", "hooks", "pre-commit")
        wrote = os.path.isfile(wrapper) and "gate.py" in (
            open(wrapper, encoding="utf-8").read() if os.path.isfile(wrapper)
            else "")
        return rc == 2 and not wrote
    finally:
        shutil.rmtree(d, True)


def _uninstall_case(mk, shutil):
    d = mk()
    try:
        hooks = os.path.join(d, ".git", "hooks")
        pre = os.path.join(hooks, "pre-commit")
        open(pre, "w", encoding="utf-8").write("#!/bin/sh\necho mine\n")
        _chmod_x(pre)
        install_chain(d)
        uninstall(d)
        body = open(pre, encoding="utf-8").read()
        return "gate.py" not in body and "echo mine" in body
    finally:
        shutil.rmtree(d, True)


def _missing_hooks_case(mk, shutil):
    d = mk()
    try:
        import shutil as _sh  # noqa: PLC0415
        _sh.rmtree(os.path.join(d, ".git", "hooks"), True)
        rc, _lines = install_chain(d)
        return rc == 2
    finally:
        shutil.rmtree(d, True)


def _selftest_entry():
    rc = activate_or_fatal()
    if rc:
        return rc
    from gate import selftest  # noqa: PLC0415
    return selftest(M("gate.title.install"), _cases())


GATE_DECL = meta("钩子安装器",
                 "把闸门入口接到 .git/hooks（链式 wrapper，不夺位）；旧装法与卸载都可逆",
                 runs_at="start-of-work",
                 off_reason="安装器是人手动跑的，不挂 pre-commit 相位")

if __name__ == "__main__":
    if "--selftest" in sys.argv[1:]:
        sys.exit(_selftest_entry())
    rc = activate_or_fatal()
    sys.exit(rc or main(sys.argv[1:]))
